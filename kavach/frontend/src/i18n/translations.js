/** Translates a district or crime-type VALUE (not a UI key) — falls back
 * to the original English string if not in the dictionary, so an
 * unrecognised value never disappears from the UI. */
export function translateValue(value, language) {
  if (language !== "kn" || !value) return value;
  return DISTRICTS_KN[value] || CRIME_TYPES_KN[value] || value;
}
